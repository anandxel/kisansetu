export function translateToDogri(enVal, hiVal) {
  if (typeof enVal === "string" && DOGRI_LOC_MAP[enVal]) {
    return DOGRI_LOC_MAP[enVal];
  }
  if (typeof hiVal === "string" && DOGRI_HI_TO_DOI_MAP[hiVal]) {
    return DOGRI_HI_TO_DOI_MAP[hiVal];
  }
  if (typeof hiVal === "string") {
    let res = hiVal;
    for (const [k, v] of Object.entries(DOGRI_HI_TO_DOI_MAP)) {
      if (res.includes(k)) {
        res = res.replaceAll(k, v);
      }
    }
    // Contextual Dogri word replacements
    res = res
      .replace(/और/g, "ते")
      .replace(/एवं/g, "ते")
      .replace(/का नाम/g, "दा नां")
      .replace(/के लिए/g, "लेई")
      .replace(/की प्रतीक्षा/g, "दी उडीक")
      .replace(/प्रतीक्षारत/g, "बकाया")
      .replace(/की पुष्टि हो गई/g, "पक्की होई गेई")
      .replace(/सत्यापित/g, "सत्यापित")
      .replace(/वर्ष/g, "साल")
      .replace(/पुरुष/g, "मर्द")
      .replace(/महिला/g, "जनानी")
      .replace(/बुक किया गया/g, "बुक कीता गेआ")
      .replace(/आपकी बुकिंग/g, "तुंदी बुकिंग")
      .replace(/रद्द/g, "रद्द")
      .replace(/संपन्न/g, "संपन्न")
      .replace(/प्रक्रियाधीन/g, "प्रक्रियाधीन");
    return res;
  }
  return enVal;
}
