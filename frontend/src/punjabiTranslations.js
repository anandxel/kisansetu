export function translateToPunjabi(enVal, hiVal) {
  if (typeof enVal === "string" && PUNJABI_LOC_MAP[enVal]) {
    return PUNJABI_LOC_MAP[enVal];
  }
  if (typeof hiVal === "string" && PUNJABI_HI_TO_PA_MAP[hiVal]) {
    return PUNJABI_HI_TO_PA_MAP[hiVal];
  }
  if (typeof hiVal === "string") {
    let res = hiVal;
    for (const [k, v] of Object.entries(PUNJABI_HI_TO_PA_MAP)) {
      if (res.includes(k)) {
        res = res.replaceAll(k, v);
      }
    }
    // Basic word translations from Hindi to Punjabi
    res = res
      .replace(/हेक्टेयर/g, "ਹੈਕਟੇਅਰ")
      .replace(/टन/g, "ਟਨ")
      .replace(/पार्सल/g, "ਪਾਰਸਲ")
      .replace(/बुकिंग/g, "ਬੁਕਿੰਗ")
      .replace(/सत्यापित/g, "ਤਸਦੀਕਸ਼ੁਦਾ")
      .replace(/गेहूं/g, "ਕਣਕ")
      .replace(/सरसों/g, "ਸਰ੍ਹੋਂ")
      .replace(/चना/g, "ਛੋਲੇ")
      .replace(/रबी/g, "ਹਾੜ੍ਹੀ")
      .replace(/खरीफ/g, "ਸਾਉਣੀ")
      .replace(/खसरा/g, "ਖਸਰਾ")
      .replace(/अलवर/g, "ਅਲਵਰ")
      .replace(/खैरली/g, "ਖੇਰਲੀ")
      .replace(/कलां/g, "ਕਲਾਂ")
      .replace(/वर्ष/g, "ਸਾਲ")
      .replace(/पुरुष/g, "ਪੁਰਸ਼")
      .replace(/महिला/g, "ਔਰਤ")
      .replace(/पुष्टि की गई/g, "ਪੁਸ਼ਟੀ ਕੀਤੀ ਗਈ")
      .replace(/बुक किया गया/g, "ਬੁੱਕ ਕੀਤਾ ਗਿਆ")
      .replace(/रद्द/g, "ਰੱਦ")
      .replace(/पूर्ण/g, "ਮੁਕੰਮਲ")
      .replace(/प्रक्रियाधीन/g, "ਪ੍ਰਕਿਰਿਆ ਅਧੀਨ")
      .replace(/प्रतीक्षारत/g, "ਉਡੀਕ ਅਧੀਨ");
    return res;
  }
  return enVal;
}
